@app.route("/export-report")
def export_report():

    # --------------------------------------------------------
    # IMPORTANT
    # --------------------------------------------------------
    # load_dataset.py uses this relative path:
    #
    # Dataset/RAW/AURA.csv
    #
    # Therefore we temporarily make the AURA root folder
    # the working directory before loading the dataset.
    # --------------------------------------------------------

    old_directory = os.getcwd()

    os.chdir(BASE_DIR)

    try:

        # Load actual AURA dataset
        dataset = load_dataset()

    finally:

        # Restore previous working directory
        os.chdir(old_directory)


    if dataset is None:

        return (
            "Unable to load Dataset/RAW/AURA.csv. "
            "Please check the dataset path."
        )


    # --------------------------------------------------------
    # GENERATE GRAPHS USING EXISTING VISUALIZATION ENGINE
    # --------------------------------------------------------

    bar_image = capture_graph(
        bar_chart,
        dataset
    )

    line_image = capture_graph(
        line_chart,
        dataset
    )

    pie_image = capture_graph(
        pie_chart,
        dataset
    )

    scatter_image = capture_graph(
        scatter_plot,
        dataset
    )

    histogram_image = capture_graph(
        histogram,
        dataset
    )

    box_image = capture_graph(
        box_plot,
        dataset
    )

    heatmap_image = capture_graph(
        heatmap,
        dataset
    )


    # --------------------------------------------------------
    # CREATE PDF
    # --------------------------------------------------------

    pdf = BytesIO()

    c = canvas.Canvas(
        pdf,
        pagesize=A4
    )

    width, height = A4


    # ========================================================
    # PAGE 1 - REPORT COVER / SUMMARY
    # ========================================================

    c.setFillColor(
        colors.HexColor("#6334F4")
    )

    c.setFont(
        "Helvetica-Bold",
        26
    )

    c.drawString(
        50,
        height - 60,
        "AURA"
    )


    c.setFillColor(
        colors.black
    )

    c.setFont(
        "Helvetica",
        13
    )

    c.drawString(
        50,
        height - 85,
        "Sales Data Analysis Report"
    )


    # Divider
    c.setStrokeColor(
        colors.HexColor("#6334F4")
    )

    c.setLineWidth(2)

    c.line(
        50,
        height - 100,
        width - 50,
        height - 100
    )


    # Dataset details
    c.setFont(
        "Helvetica-Bold",
        16
    )

    c.drawString(
        50,
        height - 145,
        "Dataset Summary"
    )


    c.setFont(
        "Helvetica",
        12
    )

    c.drawString(
        60,
        height - 180,
        f"Total Rows: {dataset.shape[0]}"
    )

    c.drawString(
        60,
        height - 205,
        f"Total Columns: {dataset.shape[1]}"
    )


    # Dataset column names
    c.setFont(
        "Helvetica-Bold",
        16
    )

    c.drawString(
        50,
        height - 250,
        "Dataset Columns"
    )


    c.setFont(
        "Helvetica",
        10
    )

    y = height - 280


    for column in dataset.columns:

        c.drawString(
            60,
            y,
            str(column)
        )

        y -= 18

        # Prevent writing outside page
        if y < 90:
            break


    # Footer
    c.setFillColor(
        colors.grey
    )

    c.setFont(
        "Helvetica-Oblique",
        9
    )

    c.drawString(
        50,
        35,
        "AURA - Sales Data Analysis"
    )


    # ========================================================
    # PAGE 2 - BAR CHART
    # ========================================================

    c.showPage()

    add_graph_page(
        c,
        width,
        height,
        "Product Sales",
        bar_image
    )


    # ========================================================
    # PAGE 3 - LINE CHART
    # ========================================================

    c.showPage()

    add_graph_page(
        c,
        width,
        height,
        "Sales Trend",
        line_image
    )


    # ========================================================
    # PAGE 4 - PIE CHART
    # ========================================================

    c.showPage()

    add_graph_page(
        c,
        width,
        height,
        "Sales Distribution by Category",
        pie_image
    )


    # ========================================================
    # PAGE 5 - SCATTER PLOT
    # ========================================================

    c.showPage()

    add_graph_page(
        c,
        width,
        height,
        "Price vs Sales",
        scatter_image
    )


    # ========================================================
    # PAGE 6 - HISTOGRAM
    # ========================================================

    c.showPage()

    add_graph_page(
        c,
        width,
        height,
        "Price Distribution",
        histogram_image
    )


    # ========================================================
    # PAGE 7 - BOX PLOT
    # ========================================================

    c.showPage()

    add_graph_page(
        c,
        width,
        height,
        "Price Distribution and Outliers",
        box_image
    )


    # ========================================================
    # PAGE 8 - HEATMAP
    # ========================================================

    c.showPage()

    add_graph_page(
        c,
        width,
        height,
        "Correlation Heatmap",
        heatmap_image
    )


    # --------------------------------------------------------
    # FINISH PDF
    # --------------------------------------------------------

    c.save()

    pdf.seek(0)


    return send_file(
        pdf,
        as_attachment=True,
        download_name="AURA_Complete_Analytics_Report.pdf",
        mimetype="application/pdf"
    )


