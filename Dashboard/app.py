# ============================================================
# CAPTURE EXISTING AURA GRAPH
# ============================================================
#
# Your existing graph functions use plt.show().
# For PDF export we don't want separate graph windows.
#
# This function temporarily disables plt.show(),
# runs the EXISTING visualization function,
# captures the graph, and returns it as an image.
#
# No graph logic is recreated here.
# ============================================================

def capture_graph(graph_function, dataset):

    # Store original show function
    original_show = plt.show

    # Prevent graph popup window
    plt.show = lambda: None

    # Clear previous figures
    plt.close("all")

    try:

        # Run existing AURA visualization
        result = graph_function(dataset)

        if result is None:
            return None

        # Get graph generated by existing function
        figure = plt.gcf()

        # Store graph in memory
        image = BytesIO()

        figure.savefig(
            image,
            format="png",
            dpi=160,
            bbox_inches="tight"
        )

        image.seek(0)

        return image

    finally:

        plt.close("all")

        # Restore plt.show()
        plt.show = original_show


# ============================================================
# ADD GRAPH PAGE TO PDF
# ============================================================

def add_graph_page(c, width, height, title, image):

    # Page title
    c.setFillColor(
        colors.HexColor("#6334F4")
    )

    c.setFont(
        "Helvetica-Bold",
        19
    )

    c.drawString(
        50,
        height - 55,
        title
    )


    # Divider line
    c.setStrokeColor(
        colors.HexColor("#6334F4")
    )

    c.setLineWidth(2)

    c.line(
        50,
        height - 72,
        width - 50,
        height - 72
    )


    # Insert graph
    if image is not None:

        c.drawImage(
            ImageReader(image),
            45,
            170,
            width=500,
            height=540,
            preserveAspectRatio=True
        )

    else:

        c.setFillColor(colors.red)

        c.setFont(
            "Helvetica",
            12
        )

        c.drawString(
            50,
            height - 130,
            "Unable to generate this visualization."
        )


    # Footer
    c.setFillColor(
        colors.grey
    )

    c.setFont(
        "Helvetica-Oblique",
        9
    )

    c.drawString(
        50,
        35,
        "Generated using AURA Visualization Engine"
    )


